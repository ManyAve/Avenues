/**
 * Writes src/styles/ui-sdk.css, ui-sdk's default stylesheet (@ui-sdk/core/web.css) scoped for Avenue.
 *
 * web.css is ui-sdk's default look, and it is global: it styles every `code`, `kbd`, `hr` and `a`, adds a
 * 4px focus outline to every `[data-slot]`, and styles parts by `data-slot` names that shadcn's
 * components use too (`button`, `field`, `dialog-content`, `select-content` and about 30 more). Loaded
 * as is, it changes Avenue's stories (AVE-16's visual diff) and would restyle Avenue's components.
 *
 * So this keeps web.css's `--ui-*` variables global (they collide with nothing of Avenue's) and puts
 * every other rule inside `@scope ([data-ui-sdk-skin])`. Avenue's own components never get ui-sdk's
 * look; a story or component that deliberately wants it (say, a ui-sdk part Avenue has not styled yet)
 * wraps itself in an element with `data-ui-sdk-skin`. Everything stays in web.css's `ui-sdk` cascade
 * layer, which avenue.css declares first, so Avenue outranks it either way.
 *
 *   bun run ui-sdk:css           # regenerate after upgrading @ui-sdk/core
 *   bun run ui-sdk:css --check   # exit 1 if the committed file is stale (run by test:scripts)
 */
import { resolve } from "node:path";

export const SKIN_ATTRIBUTE = "data-ui-sdk-skin";
const VARIABLES_SELECTOR = ":where(:root, :host) {";

/** Index of the `}` that closes the `{` at `open`, skipping strings and comments. */
function matchingBrace(css: string, open: number): number {
  let depth = 0;
  for (let i = open; i < css.length; i++) {
    const c = css[i];
    if (c === "/" && css[i + 1] === "*") {
      i = css.indexOf("*/", i + 2) + 1;
      if (i === 0) break;
    } else if (c === '"' || c === "'") {
      i = css.indexOf(c, i + 1);
      if (i === -1) break;
    } else if (c === "{") depth++;
    else if (c === "}" && --depth === 0) return i;
  }
  throw new Error("web.css: unbalanced braces");
}

/** web.css with everything but its variable block moved inside `@scope ([data-ui-sdk-skin])`. */
export function scopeWebCss(css: string, version: string): string {
  const layerStart = css.indexOf("@layer ui-sdk {");
  if (layerStart === -1) throw new Error("web.css: expected one `@layer ui-sdk { ... }` block");
  const layerOpen = css.indexOf("{", layerStart);
  const layerClose = matchingBrace(css, layerOpen);
  if (css.slice(layerClose + 1).trim() !== "" || css.slice(0, layerStart).trim() !== "") {
    throw new Error("web.css: found rules outside `@layer ui-sdk`; update scripts/ui-sdk-css.ts");
  }
  const body = css.slice(layerOpen + 1, layerClose);
  const varsStart = body.indexOf(VARIABLES_SELECTOR);
  if (varsStart === -1) throw new Error(`web.css: expected the \`${VARIABLES_SELECTOR}\` variable block`);
  const varsClose = matchingBrace(body, varsStart + VARIABLES_SELECTOR.length - 1);
  if (body.slice(0, varsStart).trim() !== "") throw new Error("web.css: rules before the variable block");
  const variables = body.slice(varsStart, varsClose + 1);
  const rules = body.slice(varsClose + 1).trim();
  return [
    `/* GENERATED by scripts/ui-sdk-css.ts from @ui-sdk/core ${version} dist/web.css. Do not edit;`,
    "   run `bun run ui-sdk:css` after upgrading @ui-sdk/core. ui-sdk's variables are global; its rules",
    `   apply only inside an element with ${SKIN_ATTRIBUTE}. Why: the header of scripts/ui-sdk-css.ts. */`,
    "@layer ui-sdk {",
    `  ${variables}`,
    "",
    `  @scope ([${SKIN_ATTRIBUTE}]) {`,
    `  ${rules}`,
    "  }",
    "}",
    "",
  ].join("\n");
}

export const paths = {
  source: resolve(import.meta.dir, "..", "node_modules/@ui-sdk/core/dist/web.css"),
  pkg: resolve(import.meta.dir, "..", "node_modules/@ui-sdk/core/package.json"),
  target: resolve(import.meta.dir, "..", "src/styles/ui-sdk.css"),
};

export async function generate(): Promise<string> {
  const { version } = (await Bun.file(paths.pkg).json()) as { version: string };
  return scopeWebCss(await Bun.file(paths.source).text(), version);
}

if (import.meta.main) {
  const expected = await generate();
  if (process.argv.includes("--check")) {
    const current = await Bun.file(paths.target).text().catch(() => "");
    if (current !== expected) {
      console.log("src/styles/ui-sdk.css is stale; run bun run ui-sdk:css");
      process.exit(1);
    }
    console.log("src/styles/ui-sdk.css matches @ui-sdk/core's web.css.");
  } else {
    await Bun.write(paths.target, expected);
    console.log("Wrote src/styles/ui-sdk.css");
  }
}
