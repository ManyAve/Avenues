/**
 * Writes src/styles/shadcn.css, a copy of shadcn's Tailwind stylesheet (`shadcn/tailwind.css`), so an app can
 * build `@manyave/avenue/styles.css` without installing shadcn itself (AVE-107).
 *
 * avenue.css used to `@import "shadcn/tailwind.css"`, but shadcn is only a dev dependency here (Avenue uses its
 * CLI to add components), and an app never installs a package's dev dependencies. Making shadcn a dependency
 * instead would put a CLI and its own dependency tree into every app for one 637-line stylesheet. So Avenue
 * keeps the stylesheet itself, byte for byte, and this script keeps the copy in step with the installed shadcn:
 *
 *   bun run shadcn:css           # regenerate after upgrading shadcn
 *   bun run shadcn:css --check   # exit 1 if the committed copy is stale (test:scripts runs the same comparison)
 *
 * The copy is verbatim, so the built CSS is identical to importing shadcn's file (visual:diff proves it).
 */
import { resolve } from "node:path";

export const paths = {
  source: resolve(import.meta.dir, "..", "node_modules/shadcn/dist/tailwind.css"),
  pkg: resolve(import.meta.dir, "..", "node_modules/shadcn/package.json"),
  target: resolve(import.meta.dir, "..", "src/styles/shadcn.css"),
};

/** shadcn's stylesheet, unchanged, under a header that says where it came from and keeps its MIT notice. */
export function copyTailwindCss(css: string, version: string): string {
  return [
    `/* GENERATED by scripts/shadcn-css.ts from shadcn ${version} dist/tailwind.css. Do not edit;`,
    "   run `bun run shadcn:css` after upgrading shadcn. Avenue keeps its own copy so an app needs no shadcn",
    "   install to build styles.css (AVE-107).",
    "   shadcn/ui, MIT License, Copyright (c) 2023 shadcn, https://github.com/shadcn-ui/ui */",
    css.endsWith("\n") ? css : `${css}\n`,
  ].join("\n");
}

export async function generate(): Promise<string> {
  const { version } = (await Bun.file(paths.pkg).json()) as { version: string };
  return copyTailwindCss(await Bun.file(paths.source).text(), version);
}

if (import.meta.main) {
  const expected = await generate();
  if (process.argv.includes("--check")) {
    const current = await Bun.file(paths.target).text().catch(() => "");
    if (current !== expected) {
      console.log("src/styles/shadcn.css is stale; run bun run shadcn:css");
      process.exit(1);
    }
    console.log("src/styles/shadcn.css matches shadcn's tailwind.css.");
  } else {
    await Bun.write(paths.target, expected);
    console.log("Wrote src/styles/shadcn.css");
  }
}
